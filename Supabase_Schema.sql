-- ==============================================================================
-- Gateway Education Services - Supabase Database Schema
-- Description: Creates the 'admissions' and 'contacts' tables with proper
--              types, default timestamps, indexes, and Row Level Security (RLS).
-- ==============================================================================

-- 1. Create the admissions table
CREATE TABLE IF NOT EXISTS public.admissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    surname VARCHAR(100) NOT NULL,
    firstname VARCHAR(100) NOT NULL,
    dateofbirth DATE,
    age INTEGER,
    classapplied VARCHAR(50) NOT NULL,
    formerschool VARCHAR(255),
    parentname VARCHAR(150) NOT NULL,
    nationality VARCHAR(100),
    phone VARCHAR(50) NOT NULL,
    email VARCHAR(150) NOT NULL,
    message TEXT,
    submission_date TIMESTAMPTZ DEFAULT timezone('utc'::text, now()),
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
);

-- 2. Create the contacts table (includes the email field)
CREATE TABLE IF NOT EXISTS public.contacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(150),
    phone VARCHAR(50),
    subject VARCHAR(100),
    message TEXT NOT NULL,
    submission_date TIMESTAMPTZ DEFAULT timezone('utc'::text, now()),
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
);

-- 3. Create indexes for quick filtering & sorting in the Supabase Dashboard
CREATE INDEX IF NOT EXISTS idx_admissions_submission_date ON public.admissions (submission_date DESC);
CREATE INDEX IF NOT EXISTS idx_admissions_email ON public.admissions (email);
CREATE INDEX IF NOT EXISTS idx_admissions_phone ON public.admissions (phone);

CREATE INDEX IF NOT EXISTS idx_contacts_submission_date ON public.contacts (submission_date DESC);
CREATE INDEX IF NOT EXISTS idx_contacts_email ON public.contacts (email);

-- 4. Enable Row Level Security (RLS) on both tables
ALTER TABLE public.admissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.contacts ENABLE ROW LEVEL SECURITY;

-- 5. Policies for Admissions
-- Allow anyone (public/anon key) to submit new admission applications
DROP POLICY IF EXISTS "Allow public insert to admissions" ON public.admissions;
CREATE POLICY "Allow public insert to admissions"
    ON public.admissions
    FOR INSERT
    TO anon, authenticated
    WITH CHECK (true);

-- Restrict SELECT/READ to authenticated users (e.g. school admin dashboard)
DROP POLICY IF EXISTS "Allow authenticated read admissions" ON public.admissions;
CREATE POLICY "Allow authenticated read admissions"
    ON public.admissions
    FOR SELECT
    TO authenticated
    USING (true);

-- 6. Policies for Contacts
-- Allow anyone (public/anon key) to submit contact messages
DROP POLICY IF EXISTS "Allow public insert to contacts" ON public.contacts;
CREATE POLICY "Allow public insert to contacts"
    ON public.contacts
    FOR INSERT
    TO anon, authenticated
    WITH CHECK (true);

-- Restrict SELECT/READ to authenticated users (e.g. school admin dashboard)
DROP POLICY IF EXISTS "Allow authenticated read contacts" ON public.contacts;
CREATE POLICY "Allow authenticated read contacts"
    ON public.contacts
    FOR SELECT
    TO authenticated
    USING (true);

-- 7. Create the newsletter_subscribers table (for newsletter subscriptions)
CREATE TABLE IF NOT EXISTS public.newsletter_subscribers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    status VARCHAR(50) DEFAULT 'subscribed',
    ip_address VARCHAR(100),
    subscribed_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()),
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
);

-- 8. Create indexes for newsletter_subscribers
CREATE INDEX IF NOT EXISTS idx_newsletter_subscribers_email ON public.newsletter_subscribers (email);
CREATE INDEX IF NOT EXISTS idx_newsletter_subscribers_subscribed_at ON public.newsletter_subscribers (subscribed_at DESC);

-- 9. Enable Row Level Security (RLS) on newsletter_subscribers
ALTER TABLE public.newsletter_subscribers ENABLE ROW LEVEL SECURITY;

-- 10. Policies for newsletter_subscribers
DROP POLICY IF EXISTS "Allow public insert to newsletter_subscribers" ON public.newsletter_subscribers;
CREATE POLICY "Allow public insert to newsletter_subscribers"
    ON public.newsletter_subscribers
    FOR INSERT
    TO anon, authenticated
    WITH CHECK (true);

DROP POLICY IF EXISTS "Allow authenticated read newsletter_subscribers" ON public.newsletter_subscribers;
CREATE POLICY "Allow authenticated read newsletter_subscribers"
    ON public.newsletter_subscribers
    FOR SELECT
    TO authenticated
    USING (true);

DROP POLICY IF EXISTS "Allow anon read newsletter_subscribers" ON public.newsletter_subscribers;
CREATE POLICY "Allow anon read newsletter_subscribers"
    ON public.newsletter_subscribers
    FOR SELECT
    TO anon
    USING (true);

-- 11. Compatibility View: newsletters (points directly to newsletter_subscribers)
CREATE OR REPLACE VIEW public.newsletters AS
SELECT id, email, status, ip_address, subscribed_at, created_at
FROM public.newsletter_subscribers;

-- Grants for API roles
GRANT ALL ON public.newsletter_subscribers TO anon, authenticated, service_role;
GRANT ALL ON public.newsletters TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

-- Comments for documentation inside Supabase
COMMENT ON TABLE public.admissions IS 'Stores student admissions applications submitted via the website';
COMMENT ON TABLE public.contacts IS 'Stores contact form inquiries submitted via the website';
COMMENT ON TABLE public.newsletter_subscribers IS 'Stores newsletter email subscriptions submitted via the website';
COMMENT ON VIEW public.newsletters IS 'Compatibility view for newsletter_subscribers';
